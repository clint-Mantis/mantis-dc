// Generates the capture DDL + config seed migrations and the app's spec.json from fields.mjs.
// Usage: node supabase/spec/generate.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PILLARS, FIELDS, RULES, LOOKUPS, EVIDENCE_TEMPLATES, LEARNER_CATEGORIES } from './fields.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a && a.length ? `array[${a.map(q).join(',')}]::text[]` : `'{}'::text[]`);

const FK = { people: 'dc_people', beneficiaries: 'dc_beneficiaries', suppliers: 'dc_suppliers', divisions: 'dc_org_divisions' };

function colDDL(fd) {
  const c = fd.key;
  switch (fd.type) {
    case 'money': return `${c} numeric(18,2) check (${c} >= 0)`;
    case 'money_signed': return `${c} numeric(18,2)`;
    case 'percent': return `${c} numeric(7,4) check (${c} between 0 and 100)`;
    case 'integer': {
      const lo = fd.min ?? 0;
      const hi = fd.max !== undefined ? ` and ${c} <= ${fd.max}` : '';
      return `${c} integer check (${c} >= ${lo}${hi})`;
    }
    case 'numeric': return `${c} numeric(18,4) check (${c} >= 0)`;
    case 'boolean': return `${c} boolean not null default false`;
    case 'text': return `${c} text`;
    case 'date': return `${c} date`;
    case 'lookup': return `${c} uuid references public.dc_lookups(id)`;
    case 'enum': return `${c} text${fd.criteria ? ' not null' : ''} check (${c} in (${fd.enum.map(q).join(',')}))`;
    case 'fk': return `${c} uuid references public.${FK[fd.fk]}(id) on delete ${fd.fk === 'divisions' ? 'set null' : 'restrict'}`;
    default: throw new Error(fd.type);
  }
}

const STD = `  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.dc_projects(id) on delete cascade,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  updated_at timestamptz not null default now(),
  updated_by uuid,
  sample_selected boolean not null default false,
  verification_status text not null default 'unverified' check (verification_status in ('unverified','sampled','queried','verified','rejected')),
  row_locked boolean not null default false,
  source text not null default 'manual' check (source in ('manual','import','carried_forward')),
  confirmed boolean not null default true,
  import_job_id uuid`;

const EXTRA = {
  dc_fin_sheet: ['unique (project_id)'],
  dc_own_shareholders: ['check (bw_pct is null or black_pct is null or bw_pct <= black_pct)'],
  dc_sd_interventions: ['check (end_date is null or start_date is null or end_date >= start_date)'],
  dc_esd_contributions: [
    'days_to_pay integer generated always as (payment_date - invoice_date) stored',
    'check (payment_date is null or invoice_date is null or payment_date >= invoice_date)',
  ],
};

// ---------------- capture DDL ----------------
let ddl = `-- GENERATED by supabase/spec/generate.mjs from supabase/spec/fields.mjs – do not edit by hand.
-- Capture tables for the 8 pillars, with standard verification columns, triggers and RLS.

`;
const tables = [];
for (const p of PILLARS) {
  const cols = FIELDS[p.code].map((fd) => '  ' + colDDL(fd));
  const extra = (EXTRA[p.table] || []).map((e) => '  ' + e);
  ddl += `create table public.${p.table} (\n${STD},\n${[...cols, ...extra].join(',\n')}\n);\n`;
  ddl += `create index ${p.table}_project_idx on public.${p.table} (project_id);\n`;
  for (const fd of FIELDS[p.code].filter((x) => x.type === 'fk' || x.type === 'lookup')) {
    ddl += `create index ${p.table}_${fd.key}_idx on public.${p.table} (${fd.key});\n`;
  }
  ddl += '\n';
  tables.push([p.table, p.code]);
}
// financial children
ddl += `create table public.dc_fin_history (
${STD},
  year_offset integer not null check (year_offset between 1 and 4),
  npat numeric(18,2),
  turnover numeric(18,2) check (turnover >= 0),
  unique (project_id, year_offset)
);
create index dc_fin_history_project_idx on public.dc_fin_history (project_id);

create table public.dc_fin_sdl_payments (
${STD},
  month_no integer not null check (month_no between 1 and 12),
  amount numeric(18,2) check (amount >= 0),
  unique (project_id, month_no)
);
create index dc_fin_sdl_payments_project_idx on public.dc_fin_sdl_payments (project_id);

`;
tables.push(['dc_fin_history', 'financial'], ['dc_fin_sdl_payments', 'financial']);

ddl += `-- triggers + RLS for every capture table
do $$
declare t text; p text;
begin
  for t, p in select x[1], x[2] from (values ${tables.map(([t, p]) => `(array['${t}','${p}'])`).join(', ')}) v(x) loop
    execute format('create trigger dc_touch before update on public.%I for each row execute function dc.touch()', t);
    execute format('create trigger dc_guard before insert or update on public.%I for each row execute function dc.capture_guard(%L)', t, p);
    execute format('create trigger dc_audit after insert or update or delete on public.%I for each row execute function dc.audit()', t);
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('create policy dc_read on public.%I for select to authenticated using (project_id in (select dc.my_projects(''read_full'')))', t);
    execute format('create policy dc_insert on public.%I for insert to authenticated with check (project_id in (select dc.my_projects(''capture'')) and (project_id in (select dc.my_projects(''manage'')) or (not row_locked and not dc.pillar_locked(project_id, %L))))', t, p);
    execute format('create policy dc_update on public.%I for update to authenticated using (project_id in (select dc.my_projects(''capture'')) and (project_id in (select dc.my_projects(''manage'')) or (not row_locked and not dc.pillar_locked(project_id, %L)))) with check (project_id in (select dc.my_projects(''capture'')) and (project_id in (select dc.my_projects(''manage'')) or (not row_locked and not dc.pillar_locked(project_id, %L))))', t, p, p);
    execute format('create policy dc_delete on public.%I for delete to authenticated using (project_id in (select dc.my_projects(''capture'')) and (project_id in (select dc.my_projects(''manage'')) or (not row_locked and not dc.pillar_locked(project_id, %L))))', t, p);
  end loop;
end $$;

-- validation trigger (BEFORE triggers fire alphabetically: dc_guard, dc_touch, dc_validate)
`;
for (const p of PILLARS) {
  ddl += `create trigger dc_validate before insert or update on public.${p.table} for each row execute function dc.validate_row('${p.code}');\n`;
}

// ---------------- seed ----------------
let seed = `-- GENERATED by supabase/spec/generate.mjs from supabase/spec/fields.mjs – do not edit by hand.
-- Configuration seed: pillars, sector codes, products, lookups, field metadata, rules, evidence templates.
-- Idempotent: safe to re-run (upserts on natural keys).

`;
seed += `insert into public.dc_pillars (code, label, table_name, criteria_key, mode, sort) values\n` +
  PILLARS.map((p) => `  (${q(p.code)}, ${q(p.label)}, ${q(p.table)}, ${q(p.criteria)}, ${q(p.mode)}, ${p.sort})`).join(',\n') +
  `\non conflict (code) do update set label = excluded.label, table_name = excluded.table_name, criteria_key = excluded.criteria_key, mode = excluded.mode, sort = excluded.sort;\n\n`;

const sectors = [['DTI', 'DTi Generic'], ['CONSTRUCTION', 'Construction'], ['FINANCE', 'Finance'], ['ICT', 'ICT'], ['PROPERTY', 'Property'], ['AGRIBEE', 'AgriBEE'], ['DEFENCE', 'Defence'], ['MAC', 'Marketing, Advertising & Communication (MAC)']];
seed += `insert into public.dc_sector_codes (code, name) values\n` + sectors.map(([c, n]) => `  (${q(c)}, ${q(n)})`).join(',\n') +
  `\non conflict (code) do update set name = excluded.name;\n\n`;
seed += `insert into public.dc_products (code, name) values ('DTI_GENERIC_CALC', 'DTi Generic Calculator Package')\non conflict (code) do update set name = excluded.name;\n\n`;

const lookupRows = [];
for (const [type, items] of Object.entries(LOOKUPS)) {
  items.forEach(([code, label], i) => {
    let meta = '{}';
    if (type === 'learning_category') meta = JSON.stringify({ learnership: LEARNER_CATEGORIES.includes(code) });
    lookupRows.push(`  (${q(type)}, ${q(code)}, ${q(label)}, ${i + 1}, ${q(meta)}::jsonb)`);
  });
}
seed += `insert into public.dc_lookups (type, code, label, sort, meta) values\n${lookupRows.join(',\n')}\non conflict (type, code) do update set label = excluded.label, sort = excluded.sort;\n\n`;

const fdRows = [];
for (const p of PILLARS) {
  FIELDS[p.code].forEach((fd, i) => {
    fdRows.push({ pillar: p.code, key: fd.key, label: fd.label, data_type: fd.type, lookup_type: fd.lookup ?? null, enum_values: fd.enum ?? null,
      enum_labels: fd.enumLabels ?? null, fk_target: fd.fk ?? null, min_value: fd.min ?? null, max_value: fd.max ?? null, required: !!fd.required,
      is_criteria: !!fd.criteria, sensitive: !!fd.sensitive, help: fd.help ?? null, sort: (i + 1) * 10, grid_visible: fd.grid !== false,
      group_name: fd.group ?? null, legacy_labels: fd.legacy ?? [] });
    const o = fdRows[fdRows.length - 1];
    for (const k of Object.keys(o)) if (o[k] === null || (o[k] === false && k !== 'grid_visible') || (Array.isArray(o[k]) && !o[k].length)) delete o[k];
    if (o.grid_visible === true) delete o.grid_visible;
  });
}
seed += `insert into public.dc_field_defs (pillar, key, label, data_type, lookup_type, enum_values, enum_labels, fk_target, min_value, max_value, required, is_criteria, sensitive, help, sort, grid_visible, group_name, legacy_labels)
select pillar, key, label, data_type, lookup_type, enum_values, enum_labels, fk_target, min_value, max_value, coalesce(required, false), coalesce(is_criteria, false), coalesce(sensitive, false), help, sort, coalesce(grid_visible, true), group_name, coalesce(legacy_labels, '{}')
  from jsonb_to_recordset(${q(JSON.stringify(fdRows).replace(/\},\{/g, '},\n{'))}::jsonb) as x(pillar text, key text, label text, data_type text, lookup_type text, enum_values text[], enum_labels text[], fk_target text, min_value numeric, max_value numeric, required boolean, is_criteria boolean, sensitive boolean, help text, sort int, grid_visible boolean, group_name text, legacy_labels text[])
on conflict (pillar, key) do update set label = excluded.label, data_type = excluded.data_type, lookup_type = excluded.lookup_type,
  enum_values = excluded.enum_values, enum_labels = excluded.enum_labels, fk_target = excluded.fk_target, min_value = excluded.min_value,
  max_value = excluded.max_value, required = excluded.required, is_criteria = excluded.is_criteria, sensitive = excluded.sensitive,
  help = excluded.help, sort = excluded.sort, grid_visible = excluded.grid_visible, group_name = excluded.group_name, legacy_labels = excluded.legacy_labels;\n\n`;

seed += `-- rules are only seeded into an empty table (edit them afterwards in the admin area)
insert into public.dc_field_rules (pillar, key, criteria_key, criteria_value, sector_code, visible, required, label_override, note)
select * from (values\n` +
  RULES.map((r) => `  (${q(r.pillar)}, ${q(r.key)}, ${q(r.criteria_key ?? null)}, ${q(r.criteria_value ?? null)}, ${q(r.sector_code ?? null)}, ${r.visible}, ${r.required === undefined ? 'null::boolean' : r.required}, ${q(r.label_override ?? null)}, ${q(r.note ?? null)})`).join(',\n') +
  `\n) v(pillar, key, criteria_key, criteria_value, sector_code, visible, required, label_override, note)\nwhere not exists (select 1 from public.dc_field_rules);\n\n`;

seed += `-- evidence templates are only seeded into an empty table
insert into public.dc_evidence_templates (sector_code, pillar, title, description, required, sort)
select null, pillar, title, description, required, sort from (values\n` +
  EVIDENCE_TEMPLATES.map(([p, t, d, r], i) => `  (${q(p)}, ${q(t)}, ${q(d)}, ${r}, ${(i + 1) * 10})`).join(',\n') +
  `\n) v(pillar, title, description, required, sort)\nwhere not exists (select 1 from public.dc_evidence_templates);\n`;

writeFileSync(join(root, 'supabase/migrations/20261120150100_dc_capture_tables.sql'), ddl);
writeFileSync(join(root, 'supabase/migrations/20261120150300_dc_seed_config.sql'), seed);
mkdirSync(join(root, 'app/src/generated'), { recursive: true });
writeFileSync(join(root, 'app/src/generated/spec.json'), JSON.stringify({ PILLARS, FIELDS, RULES, LOOKUPS, LEARNER_CATEGORIES }, null, 1));
console.log('generated', tables.length, 'tables,', fdRows.length, 'fields,', RULES.length, 'rules,', lookupRows.length, 'lookups');
